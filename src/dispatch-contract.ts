// @ts-nocheck
// Контракт диспетчера (шаг 3.16, правка от 2026-09-30).
//
// Обработчик маршрута либо ОТВЕЧАЕТ (Response), либо явно говорит «не моё»
// (`null`). `null` — единственное допустимое значение «не моё».
//
// Почему это не оформлено типами в сигнатурах: модули помечены `// @ts-nocheck`
// ради побайтового переноса, и аннотация `Response | null` там была бы
// декоративной — компилятор её не проверяет. Поэтому контракт зафиксирован
// тремя проверяемыми способами:
//   1. этот файл — единственное место, где объявлен смысл контракта;
//   2. test/dispatch-contract.test.ts — проверяет, что «не моё» это ИМЕННО null
//      (не undefined, не 0, не пустая строка), для каждого обработчика;
//   3. scripts/check-dispatch-contract.sh — запрещает безусловный
//      `return await <обработчик>(` в диспетчере: без guard следующая правка
//      снова превратит fall-through в безусловный return (дефект, пойманный
//      дифф-харнессом на /sub и /locations).

/**
 * Результат обработчика маршрута.
 *
 *  - `Response` — маршрут обслужен, ответ уходит клиенту.
 *  - `null`     — ветка не нашла себя; вызывающий обязан продолжить цепочку
 *                 маршрутов (в монолите это был переход к следующему
 *                 `else if`, а при его отсутствии — к декои-странице).
 *
 * `undefined` НЕДОПУСТИМ: он трактуется как «ответ без тела» и молча ломает
 * fall-through, потому что `if (undefined)` и `if (null)` одинаково ложны —
 * ошибка не видна в ревью, но меняет маршрутизацию.
 *
 * @typedef {Response | null} МаршрутОтвет
 */

/** Имена обработчиков, обязанных соблюдать контракт. */
