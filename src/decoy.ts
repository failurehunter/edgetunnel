export function 规范化伪装页URL(原始URL) {
	let 伪装页URL = 原始URL || 'nginx';
	if (伪装页URL && 伪装页URL !== 'nginx' && 伪装页URL !== '1101') {
		伪装页URL = 伪装页URL.trim().replace(/\/$/, '');
		if (!伪装页URL.match(/^https?:\/\//i)) 伪装页URL = 'https://' + 伪装页URL;
		if (伪装页URL.toLowerCase().startsWith('http://')) 伪装页URL = 'https://' + 伪装页URL.substring(7);
		try { const u = new URL(伪装页URL); 伪装页URL = u.protocol + '//' + u.host } catch (e) { 伪装页URL = 'nginx' }
	}
	return 伪装页URL;
}

// Reverse-proxy fallback: 1101-страница, затем проксирование на 伪装页URL,
// при неудаче — nginx-заглушка. Все ветви терминальные (как в монолите).
export async function 处理伪装页(request, url, 访问IP, UA, 伪装页URL) {
	if (伪装页URL === '1101') return new Response(await html1101(url.host, 访问IP), { status: 200, headers: { 'Content-Type': 'text/html; charset=UTF-8' } });
	try {
		const 反代URL = new URL(伪装页URL), 新请求头 = new Headers(request.headers);
		新请求头.set('Host', 反代URL.host);
		新请求头.set('Referer', 反代URL.origin);
		新请求头.set('Origin', 反代URL.origin);
		if (!新请求头.has('User-Agent') && UA && UA !== 'null') 新请求头.set('User-Agent', UA);
		const 反代响应 = await fetch(反代URL.origin + url.pathname + url.search, { method: request.method, headers: 新请求头, body: request.body, cf: request.cf });
		const 内容类型 = 反代响应.headers.get('content-type') || '';
		// 只处理文本类型的响应
		if (/text|javascript|json|xml/.test(内容类型)) {
			const 响应内容 = (await 反代响应.text()).replaceAll(反代URL.host, url.host);
			return new Response(响应内容, { status: 反代响应.status, headers: { ...Object.fromEntries(反代响应.headers), 'Cache-Control': 'no-store' } });
		}
		return 反代响应;
	} catch (error) { }
	return new Response(await nginx(), { status: 200, headers: { 'Content-Type': 'text/html; charset=UTF-8' } });
}
