// Единый логгер воркера.
//
// Проблема, которую он снимает. В монолите был один `log`, гейтированный флагом
// `调试日志打印` из env.DEBUG. При разносе на модули каждый завёл свой
// `const log = (...args) => console.error('[relay]', ...args)` — то есть вывод
// стал безусловным. На горячем пути это означает утечку адресов назначения
// клиентов (хост, порт, домен, DoH-запрос, User-Agent) плюс лишнюю стоимость
// форматирования на каждом пакете.
//
// Решение: уровень задаётся переменной окружения, по умолчанию печатаются
// только ошибки. Адреса назначения живут на уровне `debug` и по умолчанию не
// видны.
//
// Про модульное состояние. Уровень — единственное, что логгер держит в модуле,
// и он записывается присваиванием из env на каждом запросе, а не «sticky OR»
// (как было с 调试日志打印). Поэтому обновление окружения переопределяет уровень,
// и включить логирование нельзя «залипшим» флагом из предыдущего запроса.
// Альтернатива — протягивать уровень в контексте запроса во все ~90 мест вызова,
// включая те, что работают вне запроса; вклад в приватность нулевой.
//
// Уровни задаются переменной LOG_LEVEL: off | error | info | debug.
// Совместимость: DEBUG=1/true по-прежнему включает debug, как в монолите.

export const 日志等级 = {
	off: 0,
	error: 1,
	info: 2,
	debug: 3,
} as const;

export type 日志等级值 = typeof 日志等级[keyof typeof 日志等级];

const 级别别名: Record<string, 日志等级值> = {
	off: 日志等级.off, none: 日志等级.off, silent: 日志等级.off, quiet: 日志等级.off,
	error: 日志等级.error, err: 日志等级.error, warn: 日志等级.error, warning: 日志等级.error,
	info: 日志等级.info, notice: 日志等级.info,
	debug: 日志等级.debug, verbose: 日志等级.debug, trace: 日志等级.debug, all: 日志等级.debug,
};

/**
 * Приводит строку уровня к числу. Неизвестное значение даёт `error`: печатать
 * ошибки безопасно и полезно, а молчание о неверной настройке — нет.
 */
export function 规范化日志级别(值: unknown): 日志等级值 {
	const ключ = String(值 ?? '').trim().toLowerCase();
	return 级别别名[ключ] ?? 日志等级.error;
}

/** Уровень текущего изоликата. Записывается из env, не накапливается. */
let 当前级别: 日志等级值 = 日志等级.error;

/**
 * Присваивает уровень из окружения. Идемпотентно: один и тот же env даёт один и
 * тот же результат, поэтому вызов из обработчика на каждом запросе безопасен.
 */
export function 设置日志级别(env: any): void {
	if (env?.LOG_LEVEL) {
		当前级别 = 规范化日志级别(env.LOG_LEVEL);
		return;
	}
	// Совместимость с монолитом: DEBUG=1/true включал подробный вывод.
	当前级别 = ['1', 'true', 'yes', 'on'].includes(String(env?.DEBUG).toLowerCase())
		? 日志等级.debug
		: 日志等级.error;
}

export function 取日志级别(): 日志等级值 {
	return 当前级别;
}

/** Сброс к уровню по умолчанию. Для тестов. */
export function сбросить日志级别(): void {
	当前级别 = 日志等级.error;
}

/**
 * Текст ошибки, из которого вырезаны известные адреса.
 *
 * Зачем. Ошибка соединения почти всегда содержит цель: у workerd это
 * «getaddrinfo ENOTFOUND example.com». Если такое печатать на уровне `error`,
 * адрес назначения клиента утекает вопреки требованию «по умолчанию адреса не
 * логируются». При этом голое сообщение без цели бесполезно, поэтому адрес
 * заменяется заглушкой: видно, что соединение к чему-то отвалилось, но не
 * видно, к чему.
 *
 * Замена точная, по переданному списку значений, а не регулярным выражением:
 * выдуманный RE для поиска доменов дал бы ложные срабатывания на именах
 * функций и номерах портов. Длинные значения заменяются первыми, иначе короткий
 * префикс («10.0») испортил бы более длинное совпадение («10.0.0.1»).
 */
export function 安全错误(err: unknown, 敏感值: (string | undefined | null)[] = []): string {
	const 文本 = err instanceof Error ? `${err.name}: ${err.message}` : String(err);
	const 值得抹掉 = [...new Set(敏感值.filter((v): v is string => !!v && v.length > 1))];
	if (!值得抹掉.length) return 文本;
	值得抹掉.sort((a, b) => b.length - a.length);
	let 结果 = 文本;
	for (const 值 of 值得抹掉) 结果 = 结果.split(值).join('<адрес>');
	return 结果;
}

export interface 模块日志器 {
	/** Отказ, таймаут, нечитаемый ввод. Печатается по умолчанию. */
	错误(...args: any[]): void;
	/** Событие обработки без адресов. Включается LOG_LEVEL=info. */
	信息(...args: any[]): void;
	/**
	 * Подробности, в том числе адрес назначения клиента. По умолчанию выключено.
	 * Сюда уходят hostname, порт, домен, DoH-запрос, User-Agent, обратный адрес.
	 */
	调试(...args: any[]): void;
	/** Проверка уровня без построения аргументов. */
	调试已开(): boolean;
}

/**
 * Логгер с префиксом модуля: 创建日志器('relay') печатает `[relay] ...`,
 * как раньше печатали замыкания в каждом модуле.
 */
export function 创建日志器(标签: string): 模块日志器 {
	const префикс = `[${标签}]`;
	return {
		错误(...args: any[]) {
			if (当前级别 >= 日志等级.error) console.error(префикс, ...args);
		},
		信息(...args: any[]) {
			if (当前级别 >= 日志等级.info) console.log(префикс, ...args);
		},
		调试(...args: any[]) {
			if (当前级别 >= 日志等级.debug) console.log(префикс, ...args);
		},
		调试已开() {
			return 当前级别 >= 日志等级.debug;
		},
	};
}